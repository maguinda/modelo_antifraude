"""El esquema de la base en PostgreSQL (cambio 7b): el MISMO esquema que SQLite, escrito para PostgreSQL.

Las tablas se derivan del SQL de `esquema.py` (una sola fuente de verdad) con tres cambios mecánicos: `INTEGER PRIMARY KEY AUTOINCREMENT` pasa a una columna de
identidad, `REAL` a `DOUBLE PRECISION`, y los triggers de «no se edita / no se borra» (acuerdos y auditoría) se escriben como funciones de PostgreSQL.
Las migraciones de PostgreSQL llevan los MISMOS números y nombres que las de SQLite, pero solo hacen DDL: PostgreSQL nace en el esquema actual y no adopta
bases de versiones anteriores (para traer datos de SQLite está la herramienta del 7c).
"""

import re
from typing import Any, List

TRIGGER_RE = re.compile(r"^CREATE TRIGGER IF NOT EXISTS .*$", re.MULTILINE)

# (trigger, tabla, operación, mensaje): lo que en SQLite es `BEFORE UPDATE ... RAISE(ABORT, 'mensaje')`
INMUTABLES = (
    ("acuerdos_no_se_edita", "acuerdos", "UPDATE", "los acuerdos no se editan: se registra uno nuevo"),
    ("acuerdos_no_se_borra", "acuerdos", "DELETE", "los acuerdos no se borran"),
    ("auditoria_no_se_edita", "auditoria", "UPDATE", "la auditoria no se edita"),
    ("auditoria_no_se_borra", "auditoria", "DELETE", "la auditoria no se borra"),
)


def traducir_ddl(sql: str) -> List[str]:
    """Las sentencias de `sql` (SQLite) ya en PostgreSQL, una por elemento y sin los triggers (esos van aparte, ver `triggers`)."""
    sin_triggers = TRIGGER_RE.sub("", sql)
    sin_triggers = sin_triggers.replace(
        "INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    )
    sin_triggers = re.sub(r"\bREAL\b", "DOUBLE PRECISION", sin_triggers)
    return [s.strip() for s in sin_triggers.split(";") if s.strip()]


def triggers() -> List[str]:
    """Funciones y triggers que impiden editar, borrar o VACIAR (acuerdos y auditoría), repetibles.
    `TRUNCATE` no existe en SQLite y en PostgreSQL no dispara los triggers por fila: por eso lleva el suyo (por sentencia)."""
    salida: List[str] = []
    for nombre, tabla, operacion, mensaje in INMUTABLES:
        salida.append(
            f"CREATE OR REPLACE FUNCTION f_{nombre}() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION '{mensaje}' USING ERRCODE = 'integrity_constraint_violation'; END; $$"
        )
        salida.append(f"DROP TRIGGER IF EXISTS {nombre} ON {tabla}")
        salida.append(
            f"CREATE TRIGGER {nombre} BEFORE {operacion} ON {tabla} FOR EACH ROW EXECUTE FUNCTION f_{nombre}()"
        )
    for tabla, mensaje in (("acuerdos", "los acuerdos no se borran"), ("auditoria", "la auditoria no se borra")):
        salida.append(
            f"CREATE OR REPLACE FUNCTION f_{tabla}_no_se_vacia() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION '{mensaje}' USING ERRCODE = 'integrity_constraint_violation'; END; $$"
        )
        salida.append(f"DROP TRIGGER IF EXISTS {tabla}_no_se_vacia ON {tabla}")
        salida.append(
            f"CREATE TRIGGER {tabla}_no_se_vacia BEFORE TRUNCATE ON {tabla} FOR EACH STATEMENT EXECUTE FUNCTION f_{tabla}_no_se_vacia()"
        )
    return salida


def m1(con: Any, ddl: str, indices_panel: str, plataforma: int, ahora: str) -> None:
    """Migración 1 en PostgreSQL: todas las tablas, índices y triggers, y el «comercio» PLATAFORMA."""
    for s in traducir_ddl(ddl):
        con.execute(s)
    for s in triggers():
        con.execute(s)
    for s in traducir_ddl(indices_panel):
        con.execute(s)
    for nueva, tipo in (("ultimo_uso", "TEXT"), ("creada_por", "INTEGER")):
        con.execute(f"ALTER TABLE claves ADD COLUMN IF NOT EXISTS {nueva} {tipo}")
    if con.execute("SELECT 1 FROM comercios WHERE id=?", (plataforma,)).fetchone() is None:
        con.execute("INSERT INTO comercios (id, nombre, creado) VALUES (?, 'PLATAFORMA', ?)", (plataforma, ahora))
    # el id de PLATAFORMA se escribió a mano: la secuencia de identidad debe seguir DESPUÉS de él, o el próximo comercio chocaría
    con.execute(
        "SELECT setval(pg_get_serial_sequence('comercios', 'id'), (SELECT GREATEST(MAX(id), 1) FROM comercios))"
    )


def m2(con: Any) -> None:
    for nueva, tipo in (
        ("mfa_secreto", "TEXT"),
        ("mfa_confirmada", "INTEGER NOT NULL DEFAULT 0"),
        ("mfa_ultimo_paso", "INTEGER NOT NULL DEFAULT 0"),
        ("mfa_fallos", "INTEGER NOT NULL DEFAULT 0"),
        ("mfa_bloqueo_hasta", "DOUBLE PRECISION"),
    ):
        con.execute(f"ALTER TABLE claves ADD COLUMN IF NOT EXISTS {nueva} {tipo}")


def m3(con: Any, registro_modelos: str) -> None:
    for s in traducir_ddl(registro_modelos):
        con.execute(s)


def m4(con: Any, sql_portable: str) -> None:
    """`seq` es la secuencia de orden de llegada: en una base nueva de PostgreSQL no hay filas anteriores que rellenar."""
    con.execute("ALTER TABLE evaluaciones ADD COLUMN IF NOT EXISTS seq INTEGER")
    for s in traducir_ddl(sql_portable):
        con.execute(s)
    con.execute("ALTER TABLE revisiones ADD COLUMN IF NOT EXISTS minutos_resolucion DOUBLE PRECISION")
